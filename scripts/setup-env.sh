# Generate secure random secret
# Usage: generate_secret <format> [length]
# format: "hex" or "base64"
# length: bytes (default: 32)
generate_secret() {
    local format="${1:-hex}"
    local length="${2:-32}"
    local bytes
    
    if command -v openssl &> /dev/null; then
        if [ "$format" == "hex" ]; then
            openssl rand -hex "$length"
        else
            openssl rand -base64 "$length"
        fi
    elif [ -r /dev/urandom ]; then
        if [ "$format" == "hex" ]; then
            head -c "$length" /dev/urandom | xxd -p | tr -d '\n'
        else
            head -c "$length" /dev/urandom | base64 | tr -d '\n'
        fi
    else
        echo "ERROR: Neither openssl nor /dev/urandom is available" >&2
        exit 1
    fi
}

